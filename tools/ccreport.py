class CsvError(Exception):
    """The input is not a cachecliff CSV."""


class Run:  # pylint: disable=too-many-instance-attributes,too-few-public-methods
    """The data of one run of cachecliff."""

    def __init__(self, label):
        self.label = label
        self.version = ""
        self.bank = ""
        self.nfuncs = 0
        self.data_bytes = 0
        self.hz = 1_000_000_000
        self.bad = 0
        self.code = []  # (funcs, span_bytes, ns, rel_percent)
        self.data = []  # (bytes, chase_ns, chase_rel, call_ns, call_rel)
        self.skew = []  # (k, ns, rel)
        self.pattern = None  # (random_ns, repeat_ns)
        self.hot_ns = None
        self.real_hz = None  # the rate of the timer, once the times are in ticks

    def ticks(self, ns):
        """The time in timer ticks."""
        return ns * self.hz / 1e9


def parse_csv(text, label):
    """Parses the CSV lines of one run (None if there are none); the last report wins."""
    run = None
    for raw in text.splitlines():
        m = LINE_RE.search(raw.strip())
        if not m:
            continue
        kind, f = m.group(1), m.group(2).split(",")
        try:
            if kind == "cachecliff":
                run = Run(label)
                run.version, run.bank = f[0], f[1]
                run.nfuncs, run.data_bytes, run.hz = int(f[2]), int(f[3]), int(f[4])
            elif run is None:
                continue
            elif kind == "validate":
                run.bad = int(f[0])
            elif kind == "code":
                run.code.append((int(f[0]), int(f[1]), float(f[2]), int(f[3])))
            elif kind == "data":
                run.data.append(
                    (int(f[0]), float(f[1]), int(f[2]), float(f[3]), int(f[4]))
                )
            elif kind == "skew":
                run.skew.append((int(f[0]), float(f[1]), int(f[2])))
            elif kind == "pattern":
                run.pattern = (float(f[0]), float(f[1]))
            elif kind == "summary":
                run.hot_ns = float(f[0])
        except (ValueError, IndexError):
            continue  # a line cut short or damaged by the link
    return run


HEAD_RE = re.compile(
    r"cachecliff (\S+)\s+bank (\w+) \((\d+) callbacks\)\s+data (\d+) KiB\s+timer (\d+) Hz"
)
NUM = r"(\d+(?:\.\d+)?)"
KIB = r"(\d+(?:\.\d+)?|\?)"
ROW_RES = {
    "code": re.compile(rf"^(\d+)\s+{KIB}\s+{NUM}\s+{NUM}x$"),
    "data": re.compile(rf"^{NUM}\s+{NUM}\s+{NUM}x\s+{NUM}\s+{NUM}x$"),
    "skew": re.compile(rf"^(\d+)\s+{NUM}\s+{NUM}x$"),
}
SECTIONS = (
    ("code footprint", "code"),
    ("data footprint", "data"),
    ("skew of the choice", "skew"),
    ("predictability of the choice", "pattern"),
    ("summary", "summary"),
)


def add_row(run, section, g):
    """Adds the numbers of one table row of the text report to the run."""
    if section == "code":
        span = 0 if g[1] == "?" else round(float(g[1]) * 1024)
        run.code.append((int(g[0]), span, float(g[2]), round(float(g[3]) * 100)))
    elif section == "data":
        run.data.append(
            (
                round(float(g[0]) * 1024),
                float(g[1]),
                round(float(g[2]) * 100),
                float(g[3]),
                round(float(g[4]) * 100),
            )
        )
    elif section == "skew":
        run.skew.append((int(g[0]), float(g[1]), round(float(g[2]) * 100)))


def parse_report(text, label):
    """Parses the plain report that ./cachecliff prints (None if there is none)."""
    run, section, pattern = None, "", {}
    for raw in text.splitlines():
        line = raw.strip()
        head = HEAD_RE.search(line)
        if head:
            run, section, pattern = Run(label), "", {}
            run.version, run.bank = head.group(1), head.group(2)
            run.nfuncs, run.hz = int(head.group(3)), int(head.group(5))
            run.data_bytes = int(head.group(4)) * 1024
            continue
        if run is None:
            continue
        if line.startswith("validation:"):
            run.bad = 0 if line.endswith("ok") else 1
        section = next(
            (name for key, name in SECTIONS if line.startswith(key)), section
        )
        row = ROW_RES.get(section)
        m = row.match(line) if row else None
        if m:
            add_row(run, section, m.groups())
        m = re.match(rf"^(random order|repeats /\d+)\s+{NUM} ns/call", line)
        if m:
            pattern[m.group(1)[:6]] = float(m.group(2))
            if len(pattern) == 2:
                run.pattern = (pattern["random"], pattern["repeat"])
    return run


def parse(text, label):
    """Parses the CSV of ./cachecliff --csv, or else its plain report."""
    run = parse_csv(text, label) or parse_report(text, label)
    if run is None:
        raise CsvError(
            f"{label}: no cachecliff report found; run ./cachecliff --csv and give me the output"
        )
    return run


def kib(nbytes):
    """A size in KiB, as short text."""
    v = nbytes / 1024
    return f"{v:.1f}" if v < 100 else f"{v:.0f}"


def num(v):
    """A number for a table or a chart."""
    if v >= 100:
        return f"{v:.1f}"
    return f"{v:.2f}"


def ceil_nice(v):
    """The next value of the form 1, 1.2, 1.5, 2, 2.5, 3, 4, 5, 6, 8 times a power of ten."""
    if v <= 0:
        return 1
    p = 10 ** math.floor(math.log10(v))
    for m in (1, 1.2, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10):
        if m * p >= v:
            return m * p
    return 10 * p


def chart(title, xname, yname, labels, series):
    """A Mermaid xychart with one line per series."""
    top = ceil_nice(max(max(s) for s in series) * 1.05)
    xs = ", ".join(f'"{x}"' for x in labels)
    lines = [
        "```mermaid",
        "xychart-beta",
        f'    title "{title}"',
        f'    x-axis "{xname}" [{xs}]',
        f'    y-axis "{yname}" 0 --> {top:g}',
    ]
    for s in series:
        lines.append("    line [" + ", ".join(f"{v:g}" for v in s) + "]")
    lines.append("```")
    return lines


def common(runs, key):
    """The x values that every run has, in order, and a lookup per run."""
    sets = [{key(r): r for r in rows} for rows in runs]
    xs = sorted(set.intersection(*[set(s) for s in sets]))
    return xs, sets


def levels(points):
    """Splits (x, value) points into levels: a new one starts where the value
    is more than LEVEL_FACTOR times the first of the current level."""
    out = []
    for x, v in points:
        if out and v <= out[-1]["first"] * LEVEL_FACTOR:
            out[-1]["last"] = x
            out[-1]["values"].append(v)
        else:
            out.append({"x0": x, "last": x, "first": v, "values": [v]})
    for lv in out:
        lv["value"] = statistics.median(lv["values"])
    return out


def biggest_step(points):
    """The consecutive pair with the biggest ratio, as (x_before, x_after, ratio)."""
    best, best_ratio = None, 0.0
    for (xa, va), (xb, vb) in zip(points, points[1:]):
        if va > 0 and vb / va > best_ratio:
            best, best_ratio = (xa, xb, vb / va), vb / va
    return best


def knee(rows):
    """The last row of the run that starts within KNEE_PERCENT of the hot time,
    and the one after it: (within, first_beyond), either may be None."""
    within = beyond = None
    for row in rows:
        if row[-1] <= KNEE_PERCENT and beyond is None:
            within = row
        elif beyond is None:
            beyond = row
    return within, beyond


def code_findings(run, t):
    out = []
    if not run.code:
        return out
    within, beyond = knee(run.code)
    last = run.code[-1]
    if within and beyond:
        out.append(
            t["f_code_knee"].format(
                a=kib(within[1]), b=kib(beyond[1]), na=within[0], nb=beyond[0]
            )
        )
    elif within:
        out.append(
            t["f_code_nocliff"].format(
                a=kib(last[1]), r=max(r[3] for r in run.code) / 100
            )
        )
    step = biggest_step([(r[0], r[2]) for r in run.code])
    if step:
        spans = {r[0]: r[1] for r in run.code}
        out.append(
            t["f_code_step"].format(
                a=step[0],
                b=step[1],
                ka=kib(spans[step[0]]),
                kb=kib(spans[step[1]]),
                r=step[2],
            )
        )
    out.append(t["f_code_all"].format(n=last[0], r=last[3] / 100))
    return out


def data_findings(run, t):
    out = []
    if not run.data:
        return out
    chase = [(r[0], r[1]) for r in run.data]
    for i, lv in enumerate(levels(chase), 1):
        span = (
            kib(lv["x0"])
            if lv["x0"] == lv["last"]
            else f"{kib(lv['x0'])}-{kib(lv['last'])}"
        )
        tick = (
            t["tick_note"].format(k=run.ticks(lv["value"]))
            if run.hz != 1_000_000_000
            else ""
        )
        out.append(
            t["f_data_level"].format(
                n=i, span=span, v=lv["value"], tick=tick, unit=t["unit"]
            )
        )
    within, beyond = knee([(r[0], r[1], r[2]) for r in run.data])
    if within and beyond:
        out.append(t["f_data_knee"].format(a=kib(within[0]), b=kib(beyond[0])))
    last = run.data[-1]
    out.append(
        t["f_data_last"].format(a=kib(last[0]), r=last[2] / 100, c=last[4] / 100)
    )
    return out


def other_findings(run, t):
    out = []
    if len(run.skew) >= 2:
        a, b = run.skew[0], run.skew[-1]
        key = "f_skew_faster" if b[1] < a[1] else "f_skew_slower"
        out.append(t[key].format(k=b[0], r=b[1] / a[1] if a[1] else 0.0))
    if run.pattern and run.pattern[1] > 0:
        rnd, rep = run.pattern
        tick = (
            t["tick_note"].format(k=run.ticks(rnd - rep))
            if run.hz != 1_000_000_000
            else ""
        )
        out.append(
            t["f_pattern"].format(r=rnd / rep, d=rnd - rep, tick=tick, unit=t["unit"])
        )
    return out


