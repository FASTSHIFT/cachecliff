def timer_text(hz):
    """The rate of the timer, for the overview."""
    return "1 GHz (ns)" if hz == 1_000_000_000 else f"{hz / 1e6:g} MHz"


def overview(runs, t):
    head = "| " + t["target"] + " | " + " | ".join(r.label for r in runs) + " |"
    sep = "|---|" + "---|" * len(runs)
    rows = [
        (t["timer"], [timer_text(r.real_hz or r.hz) for r in runs]),
        (t["bank"], [f"{r.bank} ({r.nfuncs})" for r in runs]),
        (t["data_region"], [f"{kib(r.data_bytes)} KiB" for r in runs]),
        (t["validation"], [t["failed"] if r.bad else t["ok"] for r in runs]),
    ]
    return [head, sep] + ["| " + n + " | " + " | ".join(v) + " |" for n, v in rows]


def code_section(runs, t):
    xs, sets = common([r.code for r in runs], lambda row: row[0])
    if not xs:
        return []
    out = ["", f"## {t['code']}", ""]
    out += chart(
        t["code"], t["funcs"], t["ns_call"], xs, [[s[x][2] for x in xs] for s in sets]
    )
    out += legend(runs, t) + [""]
    cols = "".join(f" {r.label} {t['ns_call']} | {t['vs_hot']} |" for r in runs)
    out += [
        f"| {t['funcs']} | {t['code_kib']} |{cols}",
        "|---|---|" + "---|---|" * len(runs),
    ]
    for x in xs:
        cells = "".join(f" {num(s[x][2])} | {s[x][3] / 100:.2f}x |" for s in sets)
        out.append(f"| {x} | {kib(sets[0][x][1])} |{cells}")
    return out


def data_section(runs, t):
    xs, sets = common([r.data for r in runs], lambda row: row[0])
    if not xs:
        return []
    labels = [kib(x) for x in xs]
    out = ["", f"## {t['data']}", ""]
    chase = [[s[x][1] for x in xs] for s in sets]
    out += chart(
        f"{t['data']}: {t['chase']}", t["data_kib"], t["ns_load"], labels, chase
    )
    out += legend(runs, t) + [""]
    flat = sorted(v for s in chase for v in s)
    if len(flat) >= 8 and flat[-1] / max(flat[0], 1e-9) > 20:
        keep = [i for i in range(len(xs)) if max(s[i] for s in chase) <= flat[-1] / 6]
        if len(keep) >= 4:
            out += [f"{t['zoom']}:", ""]
            out += chart(
                f"{t['data']}: {t['chase']}",
                t["data_kib"],
                t["ns_load"],
                [labels[i] for i in keep],
                [[s[i] for i in keep] for s in chase],
            )
            out += [""]
    out += chart(
        f"{t['data']}: {t['call']}",
        t["data_kib"],
        t["ns_call"],
        labels,
        [[s[x][3] for x in xs] for s in sets],
    )
    out += legend(runs, t) + [""]
    cols = "".join(f" {r.label} {t['ns_load']} | {t['ns_call']} |" for r in runs)
    out += [f"| {t['data_kib']} |{cols}", "|---|" + "---|---|" * len(runs)]
    for x, lab in zip(xs, labels):
        cells = "".join(f" {num(s[x][1])} | {num(s[x][3])} |" for s in sets)
        out.append(f"| {lab} |{cells}")
    return out


def small_sections(runs, t):
    out = []
    xs, sets = common([r.skew for r in runs], lambda row: row[0])
    if xs:
        out += ["", f"## {t['skew']}", ""]
        out += chart(
            t["skew"], "skew", t["ns_call"], xs, [[s[x][1] for x in xs] for s in sets]
        )
        out += legend(runs, t)
    pats = [r for r in runs if r.pattern]
    if pats:
        out += ["", f"## {t['pattern']}", ""]
        out += ["| | random | repeat /32 |", "|---|---|---|"]
        for r in pats:
            out.append(
                f"| {r.label} | {num(r.pattern[0])} ns | {num(r.pattern[1])} ns |"
            )
    return out


def legend(runs, t):
    if len(runs) < 2:
        return []
    names = ", ".join(f"{i}. {r.label}" for i, r in enumerate(runs, 1))
    return ["", f"{t['lines']}: {names}. {t['common']}"]


def build(runs, lang, title, sources, cycles=False):
    """The Markdown report of the runs; with cycles, times are in timer ticks."""
    t = dict(TEXT[lang])
    if cycles:
        for r in runs:
            to_ticks(r)
        t["unit"] = t["cycles_unit"]
        t["ns_call"] = t["cycles_ns_call"]
        t["ns_load"] = t["cycles_ns_load"]
    out = [f"# {title or t['title']}", ""]
    out.append(f"{t['source']}: " + ", ".join(f"`{s}`" for s in sources))
    if any(r.bad for r in runs):
        out += ["", t["bad"]]
    out += ["", f"## {t['overview']}", ""] + overview(runs, t)
    out += ["", f"## {t['summary']}", ""]
    for r in runs:
        finds = code_findings(r, t) + data_findings(r, t) + other_findings(r, t)
        if len(runs) > 1:
            out.append(f"**{r.label}**")
            out.append("")
        out += [f"- {f}" for f in finds] + [""]
    out += code_section(runs, t) + data_section(runs, t) + small_sections(runs, t)
    out += [
        "",
        f"## {t['how']}",
        "",
        t["how_text"],
        "",
        t["gen"].format(ver=VERSION),
        "",
    ]
    return "\n".join(out)


def to_ticks(run):
    """Turns the times of a run from ns into timer ticks (CPU cycles on a cycle counter),
    which is what to compare between machines of different clock rates."""
    k = run.hz / 1e9
    run.code = [(a, b, c * k, d) for a, b, c, d in run.code]
    run.data = [(a, b * k, c, d * k, e) for a, b, c, d, e in run.data]
    run.skew = [(a, b * k, c) for a, b, c in run.skew]
    if run.pattern:
        run.pattern = (run.pattern[0] * k, run.pattern[1] * k)
    run.real_hz = run.hz
    run.hz = 1_000_000_000  # the values are ticks now; no second conversion


def read_inputs(paths, labels):
    """Reads the files ('-' is stdin); returns the runs and the source names."""
    runs, sources = [], []
    for i, path in enumerate(paths):
        if path == "-":
            text, name = sys.stdin.read(), "stdin"
        else:
            with open(path, encoding="utf-8", errors="replace") as f:
                text = f.read()
            name = os.path.basename(path)
        label = labels[i] if i < len(labels) else os.path.splitext(name)[0]
        runs.append(parse(text, label))
        sources.append(name)
    return runs, sources


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n", maxsplit=1)[0])
    ap.add_argument(
        "csv",
        nargs="*",
        default=["-"],
        help="CSV files of ./cachecliff --csv (- is stdin)",
    )
    ap.add_argument("-o", "--out", help="write the report here (default: stdout)")
    ap.add_argument(
        "--lang", choices=sorted(TEXT), default="zh", help="language of the text"
    )
    ap.add_argument("--title", help="title of the report")
    ap.add_argument(
        "--cycles",
        action="store_true",
        help="show timer ticks instead of ns (cycles, for comparing machines of different clocks)",
    )
    ap.add_argument(
        "-l",
        "--label",
        action="append",
        default=[],
        help="name of a file in the charts, in order",
    )
    args = ap.parse_args(argv)
    try:
        runs, sources = read_inputs(args.csv, args.label)
    except (CsvError, OSError) as exc:
        print(f"ccreport: {exc}", file=sys.stderr)
        return 2
    doc = build(runs, args.lang, args.title, sources, args.cycles)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(doc)
    else:
        sys.stdout.write(doc)
    if any(r.bad for r in runs):
        print("ccreport: the callbacks failed the validation", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
